/*
 * 結論式標籤的字典。**全站只有這一份。**
 *
 * 老師在備註欄寫的是給自己看的速記，口吻本來就直接：「他就是懶」「講不聽」。
 * 那沒有錯——問題出在這些字會流進兩份要交到別人手上的文件：
 * 親師溝通草稿（給家長讀）與學期評語（給家長讀）。
 *
 * 兩邊各自維護一份字典，遲早會走鐘：一邊補了新詞、另一邊沒補，
 * 於是同一句話在評語裡被擋、在聯絡簿裡漏出去。安全規則只能有一份。
 *
 * 收詞的標準是「幾乎沒有安全用法」。
 * 預設行為卡叫「課堂講話」，那是中性事實，收它工具就沒法用了——只收「愛講話」。
 *
 * 這份字典擋不住零數字、零關鍵詞的標籤句（例如「他就是不想學」）。
 * 它擋的是最常見、最傷人的那幾類，不是萬能過濾器。
 * 最後一道防線永遠是老師自己讀過再送出，所以兩個功能都不提供自動送出。
 */

export const LABEL_TERMS = [
  // trait：把行為說成人格。一旦寫成人格，家長就沒得討論了。
  ['trait', ['懶', '散漫', '不用心', '不認真', '態度差', '態度不佳', '態度很差',
    '沒禮貌', '沒教養', '目無尊長', '白目', '欠管教', '頑劣', '叛逆', '自私', '油條',
    '擺爛', '愛講話', '愛玩', '幼稚', '被動', '不受教', '難帶', '笨', '愚蠢', '蠢',
    '遲鈍', '孤僻', '問題學生', '沒救', '無可救藥', '放棄自己', '無心向學', '品行不佳', '操行不佳']],
  // always：全稱量詞。「總是」把一次變成永遠，而且幾乎總是不精確。
  ['always', ['總是', '老是', '每次都', '每天都', '從來不', '從來沒', '一直都',
    '動不動就', '無時無刻', '永遠都']],
  // verdict：結案式判定。話講到這裡，對話就結束了。
  ['verdict', ['屢勸不聽', '屢教不改', '講不聽', '說不聽', '本性', '個性就是',
    '就是這種', '就是這樣的孩子', '故意的', '存心', '沒有藥醫', '無可挽回']],
  // clinic：醫療診斷。老師不是醫師，這一類寫下去可能構成特種個資。
  ['clinic', ['過動', 'ADHD', '亞斯', '自閉', '憂鬱症', '躁鬱', '智能不足', '智商不高',
    '學習障礙', '情緒障礙', '有病']],
  // compare：跟別人比。家長聽到的重點會變成排名，不是自己的孩子。
  ['compare', ['全班最差', '全班最爛', '全班最', '比別人差', '其他同學都', '別人都可以',
    '同學都做得到', '倒數第一']],
];

const FLAT_TERMS = LABEL_TERMS.flatMap(([kind, terms]) =>
  terms.map((term) => ({ kind, term })));

/** 這段文字踩到哪些標籤詞。回傳空陣列代表乾淨。 */
export function labelHits(text) {
  const s = String(text || '');
  return FLAT_TERMS.filter(({ term }) => s.includes(term));
}

/**
 * 把一串文字分成「可以用的」與「被擋下的」。
 * 被擋下的要連原文帶回去——老師必須知道是哪一則被擋、為什麼，
 * 才有機會自己改寫。無聲無息地消失比擋不住還糟。
 */
export function scrubText(list) {
  const kept = [];
  const dropped = [];
  (list || []).forEach((item) => {
    const text = typeof item === 'string' ? item : item.text;
    if (!String(text || '').trim()) return;
    const hits = labelHits(text);
    if (hits.length) dropped.push({ item, hits });
    else kept.push(item);
  });
  return { kept, dropped };
}
